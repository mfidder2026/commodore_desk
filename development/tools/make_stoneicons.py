ORDER = ['editor', 'paint', 'calc', 'ping', 'chat', 'bbs', 'email', 'sid', 'radio', 'app',
         'drive', 'printer', 'trash', 'trashfull']


def glyphs(art):
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 24, (len(rows))
    rows = [r.ljust(24, '.')[:24] for r in rows]
    out = bytearray()
    for cy in range(3):
        for cx in range(3):
            for y in range(8):
                bits = rows[cy * 8 + y][cx * 8:cx * 8 + 8]
                out.append(int(''.join('1' if c == '#' else '0' for c in bits), 2))
    return out


data = bytearray()
for name in ORDER:
    data += glyphs(ICONS[name])
assert len(data) <= 126 * 8, len(data)
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, 'build', 'stoneicon.prg')
open(out, 'wb').write(bytes([0x00, 0x3c]) + data)
print('stoneicon.prg: %d icons, %d bytes' % (len(ORDER), len(data)))
