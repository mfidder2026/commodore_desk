def glyph(rows):
    out=[]
    for r in rows:
        b=0
        for c,ch in enumerate(r[:8]):
            if ch=='#': b|=1<<(7-c)
        out.append(b)
    while len(out)<8: out.append(0)
    return out

def sc(ch):
    if 'A'<=ch<='Z': return ord(ch)-64
    o=ord(ch)
    if 0x20<=o<=0x3f: return o
    return None

data=bytearray(open(BASE,'rb').read())
assert len(data)>=2048
data=data[:2048]

for ch,rows in G.items():
    code=sc(ch)
    if code is None: continue
    g=glyph(rows)
    for i in range(8):
        data[code*8+i]=g[i]

# reverse-set (128-255) = inverse van 0-127
for code in range(128):
    for i in range(8):
        data[(code+128)*8+i]=data[code*8+i]^0xff

open("data/geos.bin","wb").write(data)
print("data/geos.bin:",len(data),"bytes")

